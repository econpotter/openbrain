-- Universal capture table: every memory, note, conversation summary, and
-- document ingest event.
-- Fingerprint and structured-field design adapted from OB1:
-- docs/01-getting-started.md and schemas/enhanced-thoughts/schema.sql.

CREATE TABLE thoughts (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    content     TEXT NOT NULL,
    embedding   VECTOR(768),
    metadata    JSONB DEFAULT '{}',
    type        TEXT NOT NULL DEFAULT 'thought',
    source_type TEXT NOT NULL DEFAULT 'unknown',
    importance  SMALLINT NOT NULL DEFAULT 3
                CHECK (importance BETWEEN 0 AND 6),
    quality_score NUMERIC(5,2) NOT NULL DEFAULT 50
                CHECK (quality_score BETWEEN 0 AND 100),
    sensitivity_tier TEXT NOT NULL DEFAULT 'standard'
                CHECK (sensitivity_tier IN ('standard', 'personal', 'restricted')),
    enriched    BOOLEAN NOT NULL DEFAULT false,
    content_fingerprint TEXT,
    fts         TSVECTOR GENERATED ALWAYS AS
                    (to_tsvector('english', content)) STORED,
    created_at  TIMESTAMPTZ DEFAULT now(),
    updated_at  TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX thoughts_embedding_idx
    ON thoughts USING hnsw (embedding vector_cosine_ops);
CREATE INDEX thoughts_fts_idx ON thoughts USING gin (fts);
CREATE INDEX thoughts_type_idx ON thoughts (type);
CREATE INDEX thoughts_source_type_idx ON thoughts (source_type);
CREATE INDEX thoughts_importance_idx ON thoughts (importance DESC);
CREATE INDEX thoughts_sensitivity_tier_idx ON thoughts (sensitivity_tier);
CREATE INDEX thoughts_metadata_idx ON thoughts USING gin (metadata);
CREATE INDEX thoughts_created_at_idx ON thoughts (created_at DESC);
CREATE UNIQUE INDEX thoughts_content_fingerprint_idx
    ON thoughts (content_fingerprint)
    WHERE content_fingerprint IS NOT NULL;

-- Shared by mutable core records.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER thoughts_updated_at
    BEFORE UPDATE ON thoughts
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Merge repeated captures without discarding useful entity context. Scalar
-- keys use last-write-wins semantics. The arrays used by search and entity
-- enrichment are deduplicated unions.
CREATE OR REPLACE FUNCTION merge_thought_metadata(
    existing_metadata JSONB,
    incoming_metadata JSONB
)
RETURNS JSONB
LANGUAGE sql
IMMUTABLE
AS $$
    WITH merged AS (
        SELECT COALESCE(existing_metadata, '{}'::jsonb)
             || COALESCE(incoming_metadata, '{}'::jsonb) AS value
    ),
    array_values AS (
        SELECT key, jsonb_agg(to_jsonb(value) ORDER BY value) AS value
        FROM (
            SELECT DISTINCT arrays.key, elements.value
            FROM (
                VALUES
                    ('tags'),
                    ('topics'),
                    ('people'),
                    ('projects'),
                    ('action_items')
            ) AS arrays(key)
            CROSS JOIN LATERAL jsonb_array_elements_text(
                CASE
                    WHEN jsonb_typeof(existing_metadata->arrays.key) = 'array'
                        THEN existing_metadata->arrays.key
                    ELSE '[]'::jsonb
                END
                ||
                CASE
                    WHEN jsonb_typeof(incoming_metadata->arrays.key) = 'array'
                        THEN incoming_metadata->arrays.key
                    ELSE '[]'::jsonb
                END
            ) AS elements(value)
        ) AS deduplicated
        GROUP BY key
    )
    SELECT merged.value
        || COALESCE(
            (SELECT jsonb_object_agg(array_values.key, array_values.value)
             FROM array_values),
            '{}'::jsonb
        )
    FROM merged;
$$;

-- Canonical thought write path. Embeddings are generated by the Python
-- service before this function is called. Duplicate captures merge metadata
-- and preserve the existing embedding.
--
-- p_scalar_mode controls how a merge reconciles the numeric scalars
-- (importance, quality_score) of two captures with the same fingerprint:
--   'max'       — keep the larger value. Two humans capturing the same idea
--                 keep the stronger importance/quality signal (the default).
--   'overwrite' — the incoming value wins when provided. The deferred metadata
--                 extraction uses this so a sparse auto-capture receives the
--                 model's importance verbatim (even below the default), instead
--                 of GREATEST pinning it to the seeded default. Caller-supplied
--                 scalars are protected upstream in brain.extract_thought_metadata,
--                 which omits them from the extracted payload so they are never
--                 sent here to be overwritten.
CREATE OR REPLACE FUNCTION upsert_thought(
    p_content   TEXT,
    p_embedding VECTOR(768),
    p_metadata  JSONB DEFAULT '{}'::jsonb,
    p_type      TEXT DEFAULT NULL,
    p_scalar_mode TEXT DEFAULT 'max'
)
RETURNS JSONB
LANGUAGE plpgsql
AS $$
DECLARE
    v_fingerprint TEXT;
    v_id          UUID;
    v_inserted    BOOLEAN := false;
    v_metadata_changed BOOLEAN := false;
    v_metadata    JSONB;
    v_existing_metadata JSONB;
    v_type        TEXT;
    v_source_type TEXT;
    v_importance  SMALLINT;
    v_quality_score NUMERIC(5,2);
    v_sensitivity_tier TEXT;
    v_enriched    BOOLEAN;
    v_has_type    BOOLEAN;
    v_has_source_type BOOLEAN;
    v_has_importance BOOLEAN;
    v_has_quality_score BOOLEAN;
    v_has_sensitivity_tier BOOLEAN;
BEGIN
    IF p_scalar_mode NOT IN ('max', 'overwrite') THEN
        RAISE EXCEPTION 'upsert_thought: unknown p_scalar_mode %', p_scalar_mode;
    END IF;

    v_fingerprint := encode(sha256(convert_to(
        lower(trim(regexp_replace(p_content, '\s+', ' ', 'g'))),
        'UTF8'
    )), 'hex');

    v_metadata := COALESCE(p_metadata, '{}'::jsonb);
    v_has_type := NULLIF(p_type, '') IS NOT NULL
        OR NULLIF(v_metadata->>'type', '') IS NOT NULL;
    v_has_source_type := NULLIF(v_metadata->>'source_type', '') IS NOT NULL
        OR NULLIF(v_metadata->>'source', '') IS NOT NULL;
    v_has_importance := COALESCE(v_metadata->>'importance', '') ~ '^[0-9]+$';
    v_has_quality_score :=
        COALESCE(v_metadata->>'quality_score', '') ~ '^[0-9]+(\.[0-9]+)?$';
    v_has_sensitivity_tier :=
        v_metadata->>'sensitivity_tier' IN ('standard', 'personal', 'restricted');

    v_type := COALESCE(NULLIF(p_type, ''), NULLIF(v_metadata->>'type', ''),
                       'thought');
    v_source_type := COALESCE(NULLIF(v_metadata->>'source_type', ''),
                              NULLIF(v_metadata->>'source', ''), 'unknown');
    v_importance := CASE
        WHEN v_has_importance
            THEN LEAST(6, GREATEST(0, (v_metadata->>'importance')::numeric))::smallint
        ELSE 3
    END;
    v_quality_score := CASE
        WHEN v_has_quality_score
            THEN LEAST(100, GREATEST(0, (v_metadata->>'quality_score')::numeric))
        ELSE 50
    END;
    v_sensitivity_tier := CASE
        WHEN v_has_sensitivity_tier THEN v_metadata->>'sensitivity_tier'
        ELSE 'standard'
    END;
    v_enriched := CASE
        WHEN jsonb_typeof(v_metadata->'enriched') = 'boolean'
            THEN (v_metadata->>'enriched')::boolean
        ELSE false
    END;

    v_metadata := v_metadata || jsonb_build_object(
        'type', v_type,
        'source_type', v_source_type,
        'importance', v_importance,
        'quality_score', v_quality_score,
        'sensitivity_tier', v_sensitivity_tier,
        'enriched', v_enriched
    );

    INSERT INTO thoughts (
        content,
        content_fingerprint,
        embedding,
        metadata,
        type,
        source_type,
        importance,
        quality_score,
        sensitivity_tier,
        enriched
    )
    VALUES (
        p_content,
        v_fingerprint,
        p_embedding,
        v_metadata,
        v_type,
        v_source_type,
        v_importance,
        v_quality_score,
        v_sensitivity_tier,
        v_enriched
    )
    ON CONFLICT (content_fingerprint)
        WHERE content_fingerprint IS NOT NULL
        DO NOTHING
    RETURNING id INTO v_id;

    IF v_id IS NULL THEN
        SELECT metadata
        INTO v_existing_metadata
        FROM thoughts
        WHERE content_fingerprint = v_fingerprint;

        UPDATE thoughts
        SET metadata = merge_thought_metadata(metadata, v_metadata),
            type = CASE WHEN v_has_type THEN v_type ELSE type END,
            source_type = CASE
                WHEN v_has_source_type THEN v_source_type
                ELSE source_type
            END,
            importance = CASE
                WHEN v_has_importance AND p_scalar_mode = 'overwrite'
                    THEN v_importance
                WHEN v_has_importance THEN GREATEST(importance, v_importance)
                ELSE importance
            END,
            quality_score = CASE
                WHEN v_has_quality_score AND p_scalar_mode = 'overwrite'
                    THEN v_quality_score
                WHEN v_has_quality_score
                    THEN GREATEST(quality_score, v_quality_score)
                ELSE quality_score
            END,
            sensitivity_tier = CASE
                WHEN sensitivity_tier = 'restricted'
                     OR v_sensitivity_tier = 'restricted' THEN 'restricted'
                WHEN sensitivity_tier = 'personal'
                     OR v_sensitivity_tier = 'personal' THEN 'personal'
                ELSE 'standard'
            END,
            enriched = enriched OR v_enriched
        WHERE content_fingerprint = v_fingerprint
        RETURNING id INTO v_id;

        UPDATE thoughts
        SET metadata = metadata || jsonb_build_object(
            'type', type,
            'source_type', source_type,
            'importance', importance,
            'quality_score', quality_score,
            'sensitivity_tier', sensitivity_tier,
            'enriched', enriched
        )
        WHERE id = v_id;

        SELECT metadata IS DISTINCT FROM v_existing_metadata
        INTO v_metadata_changed
        FROM thoughts
        WHERE id = v_id;
    ELSE
        v_inserted := true;
        v_metadata_changed := true;
    END IF;

    RETURN jsonb_build_object(
        'id', v_id,
        'fingerprint', v_fingerprint,
        'inserted', v_inserted,
        'metadata_changed', v_metadata_changed
    );
END;
$$;
